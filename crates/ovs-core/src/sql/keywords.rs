fn contains(list: &[&str], word: &str) -> bool {
    let upper = word.to_ascii_uppercase();
    list.binary_search(&upper.as_str()).is_ok()
}

pub fn is_keyword(word: &str) -> bool {
    contains(KEYWORDS, word)
}

pub fn is_function(word: &str) -> bool {
    contains(FUNCTIONS, word)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lists_are_sorted_for_binary_search() {
        assert!(KEYWORDS.is_sorted(), "KEYWORDS must stay sorted");
        assert!(FUNCTIONS.is_sorted(), "FUNCTIONS must stay sorted");
    }

    #[test]
    fn lookup_is_case_insensitive() {
        assert!(is_keyword("select"));
        assert!(is_function("Group_Concat"));
        assert!(!is_keyword("customers"));
    }
}
